/**
 * lib/hidden-launch.js —— **零窗口**、**脱离宿主**地拉起 ComfyUI。
 *
 * ## 为什么需要它
 * 2026-11-04 之前，ComfyUI 由 WMI 直接创建 `cmd.exe /c .cmd` 拉起来：
 * 进程能活（WMI 服务派生，不随 DSH 退出而死），但 Windows 一定会给 cmd 分配
 * 一个控制台窗口 —— 默认终端是 Windows Terminal 时，桌面上就会多出一个
 * `DSHQP-ComfyUI` 窗口。历史上用两套"事后最小化"脚本兜（cmd 内 FindWindow、
 * 宿主侧 EnumWindows），但它们只能**把已经出现的窗口收起来**：
 *   · 窗口仍然会闪一下，任务栏里也一直留着一个条目；
 *   · Windows Terminal 把 caption 注册在自己的进程里，FindWindow 经常 `hwnd=0`；
 *   · 每次启动还白白多起一个 PowerShell 进程轮询 24 秒。
 *
 * ## 现在的做法（2026-11-05）
 * WMI 创建 `wscript.exe`（GUI 子系统，**自身没有控制台**），由一段固定 VBS 执行：
 *   `sh.Run "cmd.exe /c ""<cmd>""", 0, False`
 * 第二个参数 `0` = `SW_HIDE`：cmd 的控制台**从创建那一刻就是隐藏的**
 * （`STARTF_USESHOWWINDOW` / `SW_HIDE`），不是"先出现再藏起来"。
 * python 继承同一个隐藏控制台，所以全程零窗口。
 *
 * ## 为什么是 .cmd 而不是把命令行塞进 VBS
 * `.cmd` 能干净地承载 `set "K=V"`（launcher 需要注入 HIP_VISIBLE_DEVICES /
 * PYTHONUNBUFFERED）、任意长度的参数，以及输出重定向；把同样的东西塞进
 * VBS 字符串要穿三层引号，实测极易被吃坏。批处理以 **CRLF + UTF-8** 写入，
 * 首行 `chcp 65001` 之后 cmd 按 UTF-8 解析后续行，所以安装路径带中文/空格
 * 也能正确执行（2026-11-05 实测通过）。
 *
 * ## 进程树与"启动速度"
 * `wscript.exe → cmd.exe → python.exe`。wscript 由 WMI 创建，不在 DSH 的
 * 作业对象里：**DSH 重启不会带走后端**。下次宿主启动时 `ensureComfyUp`
 * 直接探到在线，不用再等约 45 秒的冷启动 —— 这是启动速度的最大来源。
 *
 * ## 兜底
 * 极少数环境没有 `wscript.exe`（组策略移除 Windows Script Host）。此时退回
 * 2026-11-04 的 cmd + 事后隐藏方案，**宁可闪一下窗口，也不能起不来**。
 */
import { execFile } from 'node:child_process'
import { promises as fsp } from 'node:fs'
import path from 'node:path'
import { bindAdvice, bindTest, describeBindFailure, probeComfy } from './ports.js'

export const IS_WINDOWS = process.platform === 'win32'

/** Files written next to the ComfyUI install (same base as the launch log). */
export const HIDDEN_VBS_NAME = '.dshqp-hidden.vbs'
export const LAUNCH_CMD_NAME = '.dshqp-launch.cmd'
export const PID_FILE_NAME = '.dshqp-launch.pid'
export const LEGACY_HIDE_PS1_NAME = '.dshqp-hidewin.ps1'

const WSCRIPT_PATH = path.join(process.env.SystemRoot ?? 'C:\\Windows', 'System32', 'wscript.exe')

/* ---------------------------------------------------------------- builders ---- */

/**
 * Batch body. CRLF matters: cmd's parser mis-reads LF-only files in some
 * locales (observed 2026-11-05: a LF/UTF-8 batch glued lines together and
 * raised `'5001' is not recognized`).
 */
export function buildWindowsBatch({ python, args, workdir, logPath, env = [] }) {
  const clean = (value) => String(value).replace(/"/g, '')
  const lines = [
    '@echo off',
    'chcp 65001 >nul',
    ...(env ?? []).map(([key, value]) => `set "${clean(key)}=${clean(value)}"`),
    `cd /d "${clean(workdir)}"`,
    `"${clean(python)}" ${(args ?? []).map((arg) => `"${clean(arg)}"`).join(' ')} > "${clean(logPath)}" 2>&1`,
    '',
  ]
  return lines.join('\r\n')
}

/**
 * Fixed VBS: takes the batch path as its first argument and runs it with
 * SW_HIDE. Pure ASCII, so it needs no encoding tricks; the path travels as a
 * process argument (Unicode-safe) instead of being embedded in the script.
 */
export const HIDDEN_VBS = [
  "' Hidden launcher for ComfyUI. Generated by dsh-comfy-suite.",
  "' wscript.exe is a GUI-subsystem host and owns no console; WshShell.Run",
  "' with window style 0 (SW_HIDE) makes the cmd/python console hidden from",
  "' birth, so the DSHQP-ComfyUI window never appears at all.",
  'Option Explicit',
  'Dim sh, cmdPath',
  'If WScript.Arguments.Count < 1 Then WScript.Quit 2',
  'cmdPath = WScript.Arguments(0)',
  'Set sh = CreateObject("WScript.Shell")',
  'sh.Run "cmd.exe /c """ & cmdPath & """", 0, False',
  '',
].join('\r\n')

/* ------------------------------------------------------------------- shell ---- */

function runPowerShell(script, timeoutMs = 30_000) {
  return new Promise((resolve, reject) => {
    execFile(
      'powershell',
      ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-Command', script],
      { timeout: timeoutMs, windowsHide: true, encoding: 'utf8', maxBuffer: 4 * 1024 * 1024 },
      (error, stdout, stderr) => {
        if (error !== null) {
          const detail = String(stderr ?? '').trim() || error.message
          reject(new Error(detail))
          return
        }
        resolve(String(stdout ?? '').trim())
      },
    )
  })
}

/**
 * PID of the python process running ComfyUI, or 0 when it cannot be resolved.
 *
 * Matching on the command line (rather than walking wscript → cmd → python)
 * is deliberate: WMI may insert an extra shell layer, and the 2026-10-09
 * incident showed that following parent links is the fragile part.
 * A missing pid is never fatal — callers fall back to probing `/system_stats`.
 */
export async function findComfyPid() {
  if (!IS_WINDOWS) return 0
  try {
    const script = "(Get-CimInstance Win32_Process -ErrorAction SilentlyContinue "
      + "| Where-Object { $_.CommandLine -match 'main\\.py' -and $_.Name -match 'python' } "
      + '| Select-Object -First 1 -ExpandProperty ProcessId)'
    const out = await runPowerShell(script, 10_000)
    const pid = Number.parseInt(out.split(/\s+/u).pop() ?? '', 10)
    return Number.isSafeInteger(pid) && pid > 0 ? pid : 0
  } catch {
    return 0
  }
}

/** Cheap liveness check; false for pid 0 and for processes we may not query. */
export function isProcessAlive(pid) {
  if (!Number.isSafeInteger(pid) || pid <= 0) return false
  try {
    process.kill(pid, 0)
    return true
  } catch {
    return false
  }
}

/**
 * The python pid this suite launched last, recorded next to the launch scripts.
 * It lets the settings-page launcher recognise a backend that a previous DSH
 * session (or the draw path's warm-up) started, instead of calling it "foreign".
 * Callers must still verify the pid owns port 8188 before trusting it.
 */
export async function readRecordedPid(baseDir) {
  try {
    const text = await fsp.readFile(path.join(baseDir, PID_FILE_NAME), 'utf8')
    const pid = Number.parseInt(text.trim(), 10)
    return Number.isSafeInteger(pid) && pid > 0 ? pid : 0
  } catch {
    return 0
  }
}

/* ------------------------------------------------------- Windows launch paths ---- */

/**
 * ComfyUI 的监听参数（两条启动链路都用 `--port N --listen H` 生成）。
 * 只解析不猜测：认不出就返回 0，让调用方当作"没有端口可检"。
 */
export function parseListenTarget(args) {
  const list = Array.isArray(args) ? args.map((item) => String(item)) : []
  let host = '127.0.0.1'
  let port = 0
  for (let index = 0; index < list.length; index += 1) {
    const token = list[index]
    if (token === '--port' && list[index + 1] !== undefined) {
      port = Number.parseInt(list[index + 1], 10)
    }
    else if (token.startsWith('--port=')) {
      port = Number.parseInt(token.slice('--port='.length), 10)
    }
    else if (token === '--listen' && list[index + 1] !== undefined) {
      host = list[index + 1] === '' ? '127.0.0.1' : list[index + 1]
    }
    else if (token.startsWith('--listen=')) {
      const value = token.slice('--listen='.length)
      host = value === '' ? '127.0.0.1' : value
    }
  }
  return { host, port: Number.isSafeInteger(port) && port > 0 ? port : 0 }
}

/**
 * 拉起之前先问一句：这个端口现在真的能绑吗？
 *
 * 2026-11-21 事故之前，8188 被 WinNAT/Hyper-V 保留（WinError 10013），
 * ComfyUI 每次都"启动 → 立刻退出"，启动器只能报"进程启动后立即退出，检查日志"，
 * 面板上既没有端口号也没有错误号。预检把这个死循环缩短成一条能照做的错误：
 * 端口为什么不能用、接下来该干什么。
 *
 * 三种结果：
 *   · ok                     —— 端口空着，正常拉起；
 *   · EALREADYUP             —— 端口上已经有 ComfyUI 在应答（不必再起一个）；
 *   · EACCES / EADDRINUSE 等 —— 换端口之前起不来，直接拒绝，不空等 180 秒。
 */
export async function preflightTarget(args, options = {}) {
  const bind = typeof options.bind === 'function' ? options.bind : bindTest
  const probe = typeof options.probe === 'function' ? options.probe : probeComfy
  const target = parseListenTarget(args)
  if (target.port === 0) return { ok: true, ...target, skipped: true }
  const bound = await bind(target.host, target.port, 700)
  if (bound.ok === true) return { ok: true, ...target }
  if (bound.code === 'EADDRINUSE') {
    const live = await probe(target.host, target.port, 900)
    if (live?.up === true) {
      return {
        ok: false,
        ...target,
        code: 'EALREADYUP',
        error: `ComfyUI 已经在 ${target.host}:${target.port} 上运行，无需再次启动`,
      }
    }
  }
  const advice = bindAdvice(bound.code)
  const reason = describeBindFailure(bound.code, target.port)
  return {
    ok: false,
    ...target,
    code: typeof bound.code === 'string' ? bound.code : 'EUNKNOWN',
    error: `${reason}；本次启动已取消（不必再等进程退出）${advice === '' ? '' : `。${advice}`}`,
  }
}

/**
 * Launch ComfyUI with **no console window**, detached from the DSH process tree.
 *
 * @returns {Promise<{ok: boolean, via: string, launcherPid: number, pid: number, error?: string, code?: string, port?: number}>}
 */
export async function launchComfyHidden({ python, args, workdir, logPath, baseDir, env = [] }) {
  if (!IS_WINDOWS) {
    return { ok: false, via: 'unsupported', launcherPid: 0, pid: 0, error: 'launchComfyHidden is Windows-only' }
  }
  // 端口预检：绑不上的端口不值得起进程 —— 只会得到一次崩溃 + 一条含糊的报错。
  const preflight = await preflightTarget(args)
  if (preflight.ok !== true) {
    return {
      ok: false,
      via: 'preflight',
      launcherPid: 0,
      pid: 0,
      port: preflight.port,
      code: preflight.code,
      error: preflight.error,
    }
  }
  const scriptDir = baseDir !== undefined && baseDir !== '' ? baseDir : path.dirname(logPath)
  try {
    await fsp.mkdir(scriptDir, { recursive: true })
  } catch {
    // A read-only install dir only breaks the launcher scripts; try anyway.
  }
  const cmdPath = path.join(scriptDir, LAUNCH_CMD_NAME)
  const vbsPath = path.join(scriptDir, HIDDEN_VBS_NAME)
  // The scripts are an optimisation, not a requirement: an unwritable install
  // dir (Program Files, a read-only drive) used to throw here and fail the whole
  // launch before any fallback ran. Write them where we can, and if that fails
  // step aside to a plain detached spawn instead of refusing to start.
  try {
    await fsp.writeFile(cmdPath, buildWindowsBatch({ python, args, workdir, logPath, env }), 'utf8')
    await fsp.writeFile(vbsPath, HIDDEN_VBS, 'ascii')
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error)
    const legacy = await spawnDetached(python, args, workdir, logPath)
    return { ...legacy, via: `detached (${message.slice(0, 120)})` }
  }

  const wscript = await fileExists(WSCRIPT_PATH)
  if (wscript) {
    try {
      const launcherPid = await wmiCreate(`wscript.exe //nologo "${vbsPath}" "${cmdPath}"`)
      const pid = await findComfyPid()
      await rememberPid(scriptDir, pid)
      return { ok: true, via: 'vbs', launcherPid, pid }
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error)
      // Fall through to the legacy path: a failed hide must never stop ComfyUI.
      const legacy = await launchLegacyWindows({ cmdPath, baseDir: scriptDir })
      return { ...legacy, via: `legacy (${message.slice(0, 120)})` }
    }
  }
  return launchLegacyWindows({ cmdPath, baseDir: scriptDir })
}

async function fileExists(target) {
  try {
    await fsp.access(target)
    return true
  } catch {
    return false
  }
}

/** Best-effort pid receipt; a read-only install dir must not fail a launch. */
async function rememberPid(baseDir, pid) {
  if (!Number.isSafeInteger(pid) || pid <= 0) return
  try {
    await fsp.writeFile(path.join(baseDir, PID_FILE_NAME), `${pid}\n`, 'utf8')
  } catch {
    // ignore
  }
}

/** Create a process through WMI (outside DSH's job object) and return its pid. */
async function wmiCreate(commandLine) {
  const literal = commandLine.replace(/'/g, "''")
  const script = [
    "$ErrorActionPreference = 'Stop'",
    '$r = Invoke-CimMethod -ClassName Win32_Process -MethodName Create -Arguments @{',
    `  CommandLine = '${literal}'`,
    '}',
    'if ($r.ReturnValue -ne 0) { throw "Win32_Process.Create failed, ReturnValue=$($r.ReturnValue)" }',
    'Write-Output $r.ProcessId',
  ].join('\n')
  const out = await runPowerShell(script, 30_000)
  const pid = Number.parseInt(out.split(/\s+/u).pop() ?? '', 10)
  if (!Number.isSafeInteger(pid) || pid <= 0) throw new Error(`WMI 创建进程失败：${out.slice(0, 200)}`)
  return pid
}

/**
 * 2026-11-04 的做法，仅在 wscript.exe 不可用时使用：WMI 起 cmd（窗口可见），
 * 再由宿主侧一个隐藏的 PowerShell 轮询 EnumWindows 把它收进任务栏。
 * 窗口会闪一下，但至少不会起不来。
 */
async function launchLegacyWindows({ cmdPath, baseDir }) {
  const ps1Path = path.join(baseDir, LEGACY_HIDE_PS1_NAME)
  let hideScript = ps1Path
  try {
    await fsp.writeFile(ps1Path, LEGACY_HIDE_PS1, 'ascii')
  } catch {
    // Read-only install dir: skip the cosmetic hide rather than fail the launch.
    hideScript = undefined
  }
  const launcherPid = await wmiCreate(`cmd.exe /c "${cmdPath}"`)
  const pid = await findComfyPid()
  await rememberPid(baseDir, pid)
  if (hideScript !== undefined) {
    try {
      // ⚠ 必须挂 catch：`void promise` 不吞 rejection，Node ≥15 默认会把未处理的
      //   rejection 当成致命错误**直接终止 DSH 主进程**，而这一步只是"隐藏窗口"。
      void runPowerShell(`Start-Process -FilePath 'powershell.exe' -WindowStyle Hidden -ArgumentList @(`
        + `'-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', `
        + `'-WindowStyle', 'Hidden', '-File', '${ps1Path.replace(/'/g, "''")}')`, 15_000).catch(() => { })
    } catch {
      // Best-effort: never fail a launch because the fallback hide failed.
    }
  }
  return { ok: true, via: 'legacy', launcherPid, pid }
}

/**
 * Last-resort launch when the launcher scripts cannot be written: a plain
 * detached, window-hidden spawn. No console scraping, no pid receipt from
 * ComfyUI's banner — the caller's own port probe decides when it is up.
 */
async function spawnDetached(python, args, workdir, logPath) {
  try {
    const { spawn } = await import('node:child_process')
    await fsp.mkdir(path.dirname(logPath), { recursive: true }).catch(() => { })
    const out = await fsp.open(logPath, 'a').catch(() => undefined)
    const child = spawn(python, args, {
      cwd: workdir,
      detached: true,
      windowsHide: true,
      stdio: out !== undefined ? ['ignore', out.fd, out.fd] : 'ignore',
    })
    child.unref()
    if (out !== undefined) await out.close().catch(() => { })
    const pid = child.pid ?? 0
    return { ok: true, via: 'detached', launcherPid: pid, pid: await findComfyPid().catch(() => 0) }
  } catch (error) {
    return {
      ok: false,
      via: 'detached',
      launcherPid: 0,
      pid: 0,
      error: error instanceof Error ? error.message : String(error),
    }
  }
}

/** Pure ASCII: PowerShell 5.1 reads .ps1 as ANSI when there is no BOM. */
const LEGACY_HIDE_PS1 = [
  '# Minimize the DSHQP-ComfyUI console window. Generated by dsh-comfy-suite.',
  '# MUST STAY PURE ASCII: PowerShell 5.1 reads .ps1 as ANSI without a BOM.',
  '$src = @\'',
  'using System;',
  'using System.Text;',
  'using System.Runtime.InteropServices;',
  'public class DshqpHide {',
  '  public delegate bool EnumProc(IntPtr h, IntPtr l);',
  '  [DllImport("user32.dll")] public static extern bool EnumWindows(EnumProc f, IntPtr l);',
  '  [DllImport("user32.dll", CharSet = CharSet.Unicode)] public static extern int GetWindowText(IntPtr h, StringBuilder s, int n);',
  '  [DllImport("user32.dll", CharSet = CharSet.Unicode)] public static extern int GetClassName(IntPtr h, StringBuilder s, int n);',
  '  [DllImport("user32.dll")] public static extern bool ShowWindow(IntPtr h, int c);',
  '}',
  '\'@',
  'Add-Type -TypeDefinition $src',
  '$logPath = Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) \'.dshqp-hidewin.log\'',
  'for ($i = 0; $i -lt 120; $i++) {',
  '  $script:found = [IntPtr]::Zero',
  '  $cb = [DshqpHide+EnumProc]{',
  '    param($h, $l)',
  '    $sb = New-Object System.Text.StringBuilder 512',
  '    [void][DshqpHide]::GetWindowText($h, $sb, 512)',
  '    if ($sb.ToString().Trim() -eq \'DSHQP-ComfyUI\') { $script:found = $h; return $false }',
  '    return $true',
  '  }',
  '  [void][DshqpHide]::EnumWindows($cb, [IntPtr]::Zero)',
  '  if ($script:found -ne [IntPtr]::Zero) {',
  '    $cls = New-Object System.Text.StringBuilder 256',
  '    [void][DshqpHide]::GetClassName($script:found, $cls, 256)',
  '    # Classic conhost: hide completely. Windows Terminal: minimize only (may host other tabs).',
  '    if ($cls.ToString() -eq \'ConsoleWindowClass\') { [void][DshqpHide]::ShowWindow($script:found, 0) }',
  '    else { [void][DshqpHide]::ShowWindow($script:found, 6) }',
  '    Add-Content -LiteralPath $logPath -Value ((Get-Date).ToString(\'s\') + \' handled hwnd=\' + $script:found + \' try=\' + $i) -ErrorAction SilentlyContinue',
  '    exit 0',
  '  }',
  '  Start-Sleep -Milliseconds 500',
  '}',
  'Add-Content -LiteralPath $logPath -Value ((Get-Date).ToString(\'s\') + \' not found\') -ErrorAction SilentlyContinue',
  '',
].join('\r\n')